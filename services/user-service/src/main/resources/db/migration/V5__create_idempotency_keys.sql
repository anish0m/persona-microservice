-- ===========================================================================
--  V5 — the idempotency key store.
--
--  THE PROBLEM THIS TABLE EXISTS FOR.
--
--  A client sends POST /users, the signup succeeds, and the response is lost
--  on the way back — a dropped connection, a phone leaving a lift, a gateway
--  timing out at 30s while the request took 31. The client now knows exactly
--  one thing: it has no answer. It CANNOT distinguish
--
--      (a) the request never arrived            -> retrying is correct
--      (b) it arrived and committed, reply lost -> retrying is a duplicate
--
--  and no amount of waiting separates them, because the next message could
--  always still be in flight. This is the Two Generals' Problem, and it is
--  PROVED impossible, not merely hard. So "make the client smarter" is not
--  a plan. The only reachable goal is to make the SECOND ARRIVAL HARMLESS.
--
--  WHY SIGNUP IN PARTICULAR.  POST is neither safe nor idempotent: it means
--  "create", and running it twice means creating twice. users.email UNIQUE
--  would in fact stop the second row — but it stops it with a 409, telling
--  an honest retrying client "that email is taken" when the email is taken
--  BY THEIR OWN FIRST ATTEMPT. The constraint protects the data and lies to
--  the user. This table is what turns that 409 into the original 201.
--
--  WHY THIS LANDS HARDER IN THE MICROSERVICE BUILD.
--
--  The monolith's duplicates come from one place: the client. Here they also
--  come from the INFRASTRUCTURE, and nobody chose to send them.
--
--    - The gateway on Day-17 sits between the client and user-service, and
--      gateways retry on timeout by default. A read timeout at the gateway
--      does not cancel the request still running behind it, so the retry is
--      sent while the original is mid-insert.
--    - user-service runs as SEVERAL INSTANCES. The retry is load-balanced to
--      a different instance than the original, so the two copies share no
--      JVM, no cache, no lock — nothing except this database. Any dedupe
--      that lives in process memory is invisible to the other instance, in
--      the same way and for the same reason that `synchronized` could not
--      protect the version column in V4.
--
--  So in the monolith idempotency is defensive. Here it is structural: the
--  deployment topology generates the duplicates this table absorbs, and the
--  database is the only place all the instances can agree.
-- ===========================================================================

CREATE TABLE idempotency_keys (

    -- THE SCOPE COLUMN, and the one design decision worth arguing about.
    --
    -- A key must be scoped to WHO sent it, or one client's "key-1" collides
    -- with another's and the second caller receives the first caller's
    -- response — a data leak dressed up as a cache hit. Keys are chosen by
    -- clients, so collisions are not hypothetical: "1", "test", "retry-1".
    --
    -- Everywhere else in persona the scope would be the authenticated
    -- principal. SIGNUP HAS NO PRINCIPAL — that is the whole point of it, so
    -- the scope has to come from the request itself, and the only stable
    -- identifier in a signup request is the email being registered.
    --
    -- That is weaker, and the weakness is worth naming rather than hiding:
    -- anyone may claim any email here. But what they can do with it is
    -- bounded to this table, because the stored response for an email that
    -- is already registered is a 409, not a user's data. An attacker who
    -- guesses a key learns only what a duplicate signup attempt would have
    -- told them anyway.
    scope VARCHAR(255) NOT NULL,

    -- THE CLIENT'S KEY. Generated by the CLIENT, before the first attempt.
    --
    -- It cannot be generated by the server. A server-generated key would
    -- have to be handed back in a response, and the response is precisely
    -- the thing that goes missing. The retry would arrive with no key, or
    -- with a new one, and be indistinguishable from a fresh request.
    --
    -- VARCHAR, not UUID: the server does not get to dictate the client's id
    -- format, and parsing it is not the server's business. It is an opaque
    -- token, compared byte for byte.
    idempotency_key VARCHAR(255) NOT NULL,

    -- IN_PROGRESS -> COMPLETED | FAILED.
    --
    -- The state matters because a retry can arrive while the first attempt
    -- is STILL RUNNING. A two-state design (present/absent) cannot express
    -- that: "present" would have to mean "finished", and the row exists
    -- before the work does.
    --
    -- A CHECK rather than a Postgres ENUM type. An enum needs ALTER TYPE to
    -- grow and the type outlives the table; a CHECK is readable in \d and
    -- changed by an ordinary migration.
    status VARCHAR(20) NOT NULL
        CHECK (status IN ('IN_PROGRESS', 'COMPLETED', 'FAILED')),

    -- THE FINGERPRINT — a hash of the request body.
    --
    -- A key identifies an INTENT, not a payload, and the two can disagree:
    -- same key with a DIFFERENT body is a client bug (a reused key), and
    -- replaying the first response for it would silently discard the second
    -- request. Detect it and reject with 422; do not guess.
    --
    -- Note the direction. We never dedupe BY content — two genuinely
    -- distinct intents can be byte-identical, and the key is what separates
    -- them. The fingerprint only validates a key the client already chose.
    request_fingerprint VARCHAR(64) NOT NULL,

    -- THE STORED REPLY. Null while IN_PROGRESS — there is no answer yet.
    --
    -- The status code is stored alongside the body because replaying a 201
    -- as a 200 is a different answer, and a client that keys off the status
    -- would see the retry as a different outcome. Idempotency is about
    -- state, but a replay should be indistinguishable, so we keep both.
    response_status INTEGER,
    response_body   TEXT,

    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),

    -- THE COMPOSITE PRIMARY KEY, AND IT IS THE ACTUAL MECHANISM.
    --
    -- The obvious implementation is: look the key up, and if absent, do the
    -- work and store it. That has a gap. Two copies of the same request can
    -- both look up, both find nothing, and both proceed — which is Day-10's
    -- lost update wearing different clothes. The check is correct and still
    -- lets a duplicate through, exactly as users.email's Java check does.
    --
    -- So the LOOKUP IS NOT THE GATE. THE INSERT IS. A request claims its key
    -- by inserting IN_PROGRESS; the constraint decides, at write time, with
    -- the row locked, which of the racing copies is the first. There is no
    -- window, because asking and acting are one statement.
    --
    -- Same shape as users.email UNIQUE: application code races, the
    -- constraint does not.
    PRIMARY KEY (scope, idempotency_key)
);

COMMENT ON TABLE idempotency_keys IS
    'Deduplicates retried unsafe requests. A row is claimed by INSERT before the work runs, so the primary key - not an application lookup - decides which concurrent copy is first.';

COMMENT ON COLUMN idempotency_keys.scope IS
    'Who the key belongs to. The signup endpoint is unauthenticated, so this is the email being registered rather than a principal.';

COMMENT ON COLUMN idempotency_keys.request_fingerprint IS
    'Hash of the request body. Same key with a different body is a client error (422), never a replay.';

-- NOT CREATED HERE: an index on created_at for expiry.
--
-- Rows must eventually be deleted — the table grows forever otherwise, and
-- every delete is a bet that no legitimate retry outlives the window. But
-- persona has no scheduled job to do the deleting, and an index that no
-- query uses is pure write cost on every insert. It arrives with the job
-- that needs it, not before.
